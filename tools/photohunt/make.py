#!/usr/bin/env python3
# Builds the bundled Photo Hunt pairs from assets/originals/photohunt/NN-<id>.jpg:
# crop screenshot chrome, paint out watermarks, denoise/sharpen, resize, apply the five
# differences from pairs.py, write assets/photohunt/<id>.left|right.webp and src/data/photoHuntPairs.js.
# Needs: pip install opencv-python-headless pillow numpy.   Usage: python3 tools/photohunt/make.py [--preview DIR]
import glob,json,os,sys,numpy as np,cv2
from PIL import Image, ImageFilter
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from pairs import PAIRS
ROOT=os.path.abspath(os.path.join(os.path.dirname(__file__),'..','..'))
MAX=1200
def clean(path,c):
  a=cv2.imread(path);h,w=a.shape[:2]
  if c.get('star'):  # Gemini sparkle sits 150px in from the bottom-right corner
    yy,xx=np.mgrid[0:h,0:w];cx,cy,R=w-150,h-150,66
    m=((np.abs(xx-cx)/R)**(2/3)+(np.abs(yy-cy)/R)**(2/3)<=1).astype(np.uint8)*255
    a=cv2.inpaint(a,cv2.dilate(m,np.ones((9,9),np.uint8)),9,cv2.INPAINT_TELEA)
  l,t,r,b=c['crop'];a=a[t:h-b,l:w-r]
  if c.get('dn'):a=cv2.fastNlMeansDenoisingColored(a,None,c['dn'],c['dn'],7,21)
  h,w=a.shape[:2];k=MAX/max(w,h);a=cv2.resize(a,(round(w*k),round(h*k)),interpolation=cv2.INTER_AREA)
  im=Image.fromarray(cv2.cvtColor(a,cv2.COLOR_BGR2RGB)).filter(ImageFilter.UnsharpMask(radius=1.4,percent=70,threshold=2))
  return cv2.cvtColor(np.asarray(im),cv2.COLOR_RGB2BGR).astype(np.float32)
def webp(img,path):Image.fromarray(cv2.cvtColor(np.clip(img,0,255).astype(np.uint8),cv2.COLOR_BGR2RGB)).save(path,'WEBP',quality=84,method=6)
preview=sys.argv[sys.argv.index('--preview')+1] if '--preview' in sys.argv else None
out=[]
for n,(pid,title,source,cfg,edits) in enumerate(PAIRS):
  src=glob.glob(f'{ROOT}/assets/originals/photohunt/{n:02d}-{pid}.jpg')[0]
  left=clean(src,cfg);right=left.copy();regs=edits(right);H,W=left.shape[:2]
  webp(left,f'{ROOT}/assets/photohunt/{pid}.left.webp');webp(right,f'{ROOT}/assets/photohunt/{pid}.right.webp')
  # r is in image-width units; the game measures taps the same way (aspect-corrected).
  regions=[{'x':round(x/W,4),'y':round(y/H,4),'r':round(min(.14,max(.04,(r*1.15+6)/W)),4)} for x,y,r in regs]
  out.append({'id':'ph-'+pid,'title':title,'source':source,'leftKey':f'photohunt:{pid}:left','rightKey':f'photohunt:{pid}:right','regions':regions})
  if preview:
    v=np.clip(right,0,255).astype(np.uint8).copy()
    for g in regions:cv2.circle(v,(int(g['x']*W),int(g['y']*H)),int(g['r']*W),(0,255,255),2)
    cv2.imwrite(f'{preview}/{pid}.jpg',np.hstack([left.astype(np.uint8),v]),[cv2.IMWRITE_JPEG_QUALITY,85])
  print(pid,W,H,len(regions))
js='// Generated by tools/photohunt/make.py from assets/originals/photohunt (owner photos, cleaned up,\n// five differences each). build.mjs embeds assets/photohunt/<id>.left|right.webp under these ART keys.\nconst PHOTO_HUNT_PAIRS=[\n'+',\n'.join(' '+json.dumps(p,ensure_ascii=False,separators=(',',':')) for p in out)+'\n];\n\nObject.assign(exports,{PHOTO_HUNT_PAIRS});\n'
open(f'{ROOT}/src/data/photoHuntPairs.js','w').write(js)
