const GLYPHS=new Map();
for(const block of ART.trim().split(/\n\s*\n/)){
 const lines=block.split('\n'),key=lines[0],rows=lines.slice(1);
 const bits=new Uint8Array(64);
 rows.slice(0,8).forEach((row,y)=>{for(let x=0;x<8;x++)if(row[x]==='#')bits[y*8+x]=1;});
 GLYPHS.set(key,bits);
}
// Accents and punctuation the font does not have collapse to the closest cell.
function gbText(s){
 return String(s??'').replace(/[‘’`]/g,"'").replace(/[“”]/g,'"').replace(/[–—·]/g,'-').replace(/POKéMON|Pokémon|POKEMON/g,'POKéMON').replace(/[ÉÈÊ]/g,'E').normalize("NFD").replace(/é/g,'é').replace(/[̀-ͯ]/g,'').replace(/[^\x20-\x7e\n é×¥…▶▷▼▲♂♀①②③④⑤♪]/g,'');
}
// Color atlases are built lazily per CSS colour; drawing is a drawImage per cell.
const atlases=new Map(),ORDER=[...GLYPHS.keys()];
function atlas(color){
 if(atlases.has(color))return atlases.get(color);
 const c=document.createElement('canvas');c.width=ORDER.length*8;c.height=8;const x=c.getContext('2d');x.fillStyle=color;
 ORDER.forEach((k,i)=>{const b=GLYPHS.get(k);for(let p=0;p<64;p++)if(b[p])x.fillRect(i*8+(p&7),p>>3,1,1);});
 const index=new Map(ORDER.map((k,i)=>[k,i]));const a={c,index};atlases.set(color,a);return a;
}
function drawText(ctx,text,x,y,color='#000'){
 const a=atlas(color);let cx=x,cy=y;
 for(const ch of gbText(text)){if(ch==='\n'){cx=x;cy+=16;continue;}const i=a.index.get(ch);if(i!==undefined)ctx.drawImage(a.c,i*8,0,8,8,cx,cy,8,8);cx+=8;}
}
const textWidth=s=>gbText(s).length*8;
// Word-wrap into lines of at most `cols` cells (the battle text box holds 18).
function wrapText(text,cols=18){
 const out=[];for(const para of gbText(text).split('\n')){let line='';for(const word of para.split(' ')){if(!word)continue;if(!line)line=word;else if(line.length+1+word.length<=cols)line+=' '+word;else{out.push(line);line=word;}while(line.length>cols){out.push(line.slice(0,cols));line=line.slice(cols);}}out.push(line);}
 return out;
}
Object.assign(exports,{GLYPHS,gbText,drawText,textWidth,wrapText});
